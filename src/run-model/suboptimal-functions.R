eval_policy_optimality <- function(P, R, discount, Vpolicy, epsilon = 0.01) { # Modification of mdp_eval_policy_optimality (MDPToolbox) to allow
  # user-defined epsilon. The rest of the function is left untouched.
  # In the absence of epsilon input, defaults to 0.01 as in the
  # original function.
  
  if (discount <= 0 | discount > 1) {
    print("--------------------------------------------------------")
    print("ERROR: Discount rate must be in ]0; 1]")
    print("--------------------------------------------------------")
  } else if (ifelse(is.list(P), length(Vpolicy) != dim(P[[1]])[1],
                    FALSE
  )) {
    print("--------------------------------------------------------")
    print("ERROR: policy must have the same dimension as P")
    print("--------------------------------------------------------")
  } else if (ifelse(!is.list(P), length(Vpolicy) != dim(P)[1],
                    FALSE
  )) {
    print("--------------------------------------------------------")
    print("MDP Toolbox ERROR: policy must have the same dimension as P")
    print("--------------------------------------------------------")
  } else {
    PR <- mdp_computePR(P, R)
    if (is.list(P)) {
      S <- dim(P[[1]])[1]
      A <- length(P)
      Q <- matrix(0, S, A)
      for (a in 1:A) {
        Q[, a] <- as.matrix(PR[, a] + discount * P[[a]] %*%
                              Vpolicy)
      }
    } else {
      S <- dim(P)[1]
      A <- dim(P)[3]
      Q <- matrix(0, S, A)
      for (a in 1:A) {
        Q[, a] <- PR[, a] + discount * P[, , a] %*% Vpolicy
      }
    }
    optimal_actions <- abs(Q - matrix(
      rep(Vpolicy, A), length(Vpolicy),
      A
    )) < epsilon
    
    if (max(colSums(optimal_actions)) == 1) {
      is_multiple <- F
    } else {
      is_multiple <- T
    }
    return(list(multiple = is_multiple, optimal_actions = optimal_actions))
  }
} # end eval_policy_optimality

convertNOP_epsilon <- function(nop_matrix, epsilon) {
  # Converts the optimal_actions output of eval_policy_optimality() OR
  # mdp_eval_policy_optimality() into a data frame whose rows contain
  # one state-action pair, along with the epsilon value used in the calculation
  # of optimal_actions
  #
  # INPUT
  # nop_matrix : near-optimal policy matrix, whose rows are states, whose
  #              columns are actions, and whose values are logical (matrix)
  # epsilon    : threshold for near-optimality (double)
  #
  # OUTPUT
  # A data frame whose rows contain one state-action pair, along with the
  # epsilon value used in the calculation of optimal_actions
  ##
  
  # Create data frame to hold state & column index of near-optimal actions
  n_rows <- length(which(nop_matrix == TRUE)) # TRUE means near-optimal
  nop_df <- NULL
  
  # Populate the data frame
  n_states <- dim(nop_matrix)[1]
  for (s in 1:n_states) {
    act_ind <- which(nop_matrix[s, ] == TRUE) # vector of action indices
    state <- rep(s, length(act_ind)) # same-length vector of states
    eps <- rep(epsilon, length(act_ind))
    
    nop_df <- rbind(nop_df, cbind(eps, state, act_ind))
  }
  
  colnames(nop_df) <- c("epsilon", "state", "act_ind")
  return(data.frame(nop_df))
} # end convertNOP_epsilon

n_near_optimal <- function(P, R, V, d, n, epsilon = 0.01,
                           eps_increment = 0.001, result = NULL) {
  # For a given MDP and the values of its optimal policy, find at least
  # the first n near-optimal (within epsilon of optimal) actions for each
  # state (NOTE: this function is slow!)
  #
  # INPUT
  # P : Array of transition matrices where slice [,,a] holds transition
  #     probabilities between each set of states under action a
  # R : Array of reward matrices where slice [,,a] holds reward
  #     values for each state under action a
  # V : Values associated with each state under the optimal policy (vector)
  # d : the discount factor used to find the optimal policy (double)
  # n : number of near-optimal policies to find (integer)
  # epsilon       : Near-optimality threshold (double)
  # eps_increment : Amount by which to increase epsilon at every recursive
  #               : call (double)
  # result        : States and IDs of near-optimal actions (data frame)
  #
  # OUTPUT
  # A data frame with the following columns:
  #   epsilon
  #   state
  #   act_ind
  #
  # ASSUMPTIONS
  # * the following functions are already sourced:
  #    eval_policy_optimality()
  #    convertNOP_epsilon()
  # * pr_list contains the following elements:
  #   P : array of transition (probability) matrices
  #   R : array of reward matrices
  ##
  
  # Find actions that are within epsilon of optimal
  nop <- eval_policy_optimality(P, R, d, V, epsilon)$optimal_actions
  
  # convert to data frame
  nop_df <- convertNOP_epsilon(nop, epsilon)
  result <- rbind(result, nop_df)
  
  # Keep only rows that aren't duplicated in state and act_ind
  result <- result[which(!duplicated(result[, c("state", "act_ind")])), ]
  
  # Keep only the first (up to) n rows containing each state
  keep_rows <- NULL
  for (s in unique(result$state)) { # slow but this function is already slow.
    # will only ever loop 6 times per function call
    keep_rows <- rbind(
      keep_rows,
      na.omit(result[which(result$state == s)[1:n], ])
    )
  }
  result <- keep_rows
  
  # Check whether enough near-optimal policies have been found
  min_nop <- min(rowSums(nop))
  
  # Disallow n > number of possible actions
  if (n > dim(nop)[2]) {
    message("Requested number of near-optimal actions exceeds total actions. Returning all possible actions as near-optimal.")
  }
  n <- min(n, dim(nop)[2])
  
  if (min_nop < n) {
    # At least one state doesn't have enough near-optimal policies
    
    # increment the epsilon value. This can't be done with simple addition
    # because the R representation of the sum is often a little bit (~10^-17)
    # off from the mathematically correct value. Round to the correct value,
    # matching the the precision of eps_increment
    precision <- nchar(strsplit(as.character(eps_increment), "\\.")[[1]][2])
    epsilon <- round(epsilon + eps_increment, precision)
    
    result <- n_near_optimal(P, R, V, d, n, epsilon, eps_increment, result)
    return(result)
  } else { # enough near-optimal policies were found
    return(result)
  }
} # end n_near_optimal
